/* -----------------------------------------------------------------------
 *  C struct for kernel state (used as ObjC ivars via preprocessor)
 * ----------------------------------------------------------------------- */

struct _MaxxwellKernel_class_t;

struct MaxxwellKernel {
    struct _MaxxwellKernel_class_t *isa;
    BOOL                _initialized;
    BOOL                _running;
    uint32_t            _boot_flags;
    char                _userfs_root[512];
    pid_t               _kernel_pid;
    pid_t               _init_pid;
    mach_port_t         _host_port;
    mach_port_t         _host_priv_port;
    mach_port_t         _kernel_port;
    struct termios      _saved_term;
    BOOL                _have_saved_term;
};

typedef struct MaxxwellKernel MaxxwellKernel;

